CREATE MATERIALIZED VIEW mv_squad_statistics AS
WITH series_outcomes AS (
    SELECT sc.home_squad_id AS squad_id, result.outcome,
           CASE WHEN result.outcome = 'home_win' THEN 1 ELSE 0 END AS wins,
           CASE WHEN result.outcome = 'away_win' THEN 1 ELSE 0 END AS losses,
           CASE WHEN result.outcome = 'draw' THEN 1 ELSE 0 END AS draws
    FROM scrims sc JOIN scrim_results result ON result.scrim_id = sc.id
    WHERE result.outcome <> 'void'
    UNION ALL
    SELECT sc.away_squad_id, result.outcome,
           CASE WHEN result.outcome = 'away_win' THEN 1 ELSE 0 END,
           CASE WHEN result.outcome = 'home_win' THEN 1 ELSE 0 END,
           CASE WHEN result.outcome = 'draw' THEN 1 ELSE 0 END
    FROM scrims sc JOIN scrim_results result ON result.scrim_id = sc.id
    WHERE result.outcome <> 'void'
)
SELECT
    s.id AS squad_id,
    s.public_number AS squad_number,
    s.name AS squad_name,
    s.acronym AS squad_acronym,
    level.name AS squad_level,
    region.name AS region_name,
    COALESCE(sum(o.wins), 0)::integer AS wins,
    COALESCE(sum(o.losses), 0)::integer AS losses,
    COALESCE(sum(o.draws), 0)::integer AS draws,
    count(o.squad_id)::integer AS completed_scrims,
    round(100.0 * COALESCE(sum(o.wins), 0) / NULLIF(count(o.squad_id), 0), 2) AS win_rate_percent
FROM squads s
JOIN squad_levels level ON level.code = s.level_code
JOIN regions region ON region.code = s.region_code
LEFT JOIN series_outcomes o ON o.squad_id = s.id
GROUP BY s.id, s.public_number, s.name, s.acronym, level.name, region.name;
CREATE UNIQUE INDEX mv_squad_statistics_pk ON mv_squad_statistics (squad_id);
COMMENT ON MATERIALIZED VIEW mv_squad_statistics IS '11A. Stored, denormalized squad totals for cards and profiles. Refresh after finalizing/correcting results.';

