-- ABYSS: PostgreSQL schema based on ABYSS.pdf (42 pages).
-- Fresh database design, NOT an in-place migration of the earlier two tables.
-- Related entity tables are 3NF; vw_/mv_ objects are display-ready data.
-- Read DESIGN.md for REQUIRED command-handler invariants and projection behavior.
-- UUIDs can be supplied by the application; gen_random_uuid() is the fallback.
-- All instants use timestamptz. Handlers maintain updated_at and aggregate versions.
BEGIN;

-- 1. ACCOUNT AND ACCESS
-- Under this section: individual login identities and platform privileges.
CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    username VARCHAR(50) NOT NULL CHECK (length(trim(username)) > 0),
    email VARCHAR(254) NOT NULL,
    password_hash TEXT NOT NULL,
    display_name VARCHAR(100),
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','suspended','closed')),
    email_verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0)
);
CREATE UNIQUE INDEX users_username_ci ON users (lower(username));
CREATE UNIQUE INDEX users_email_ci ON users (lower(email));
COMMENT ON TABLE users IS '1. Accounts: individual sign-in identities; never share a squad password.';
COMMENT ON COLUMN users.password_hash IS 'Password hash only; never plaintexmvt or reversible encryption.';
CREATE TABLE user_roles (
    user_id UUID NOT NULL REFERENCES users(id),
    role TEXT NOT NULL CHECK (role IN ('representative','moderator','admin')),
    granted_by UUID REFERENCES users(id),
    granted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, role)
);
COMMENT ON TABLE user_roles IS '1. Platform roles. Guests have no account or guest role row.';
CREATE TABLE auth_tokens (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES users(id),
    purpose TEXT NOT NULL CHECK (purpose IN ('refresh','verify_email','reset_password')),
    token_hash TEXT NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (expires_at > created_at)
);
CREATE INDEX auth_tokens_user ON auth_tokens (user_id, purpose);
CREATE INDEX auth_tokens_expiry ON auth_tokens (expires_at);
COMMENT ON TABLE auth_tokens IS '1. Hashed session/reset/verification tokens; consume or rotate atomically.';

-- 2. REFERENCE DATA AND UPLOADED FILES
-- Under this section: editable catalogs. MLBB ranks, squad levels and ABYSS ratings differ.
CREATE TABLE regions (
    code VARCHAR(20) PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    default_timezone TEXT NOT NULL
);
COMMENT ON TABLE regions IS '2. Matchmaking regions and IANA timezone defaults.';
CREATE TABLE game_ranks (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL UNIQUE,
    sort_order SMALLINT NOT NULL UNIQUE
);
COMMENT ON TABLE game_ranks IS '2. MLBB rank catalog; seed from an approved list rather than mockup values.';
CREATE TABLE squad_levels (
    code VARCHAR(30) PRIMARY KEY,
    name VARCHAR(60) NOT NULL,
    verification_required BOOLEAN NOT NULL DEFAULT false
);
COMMENT ON TABLE squad_levels IS '2. Squad classification, e.g. Amateur or Collegiate, independent of MLBB rank.';
CREATE TABLE heroes (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT true
);
COMMENT ON TABLE heroes IS '2. Hero catalog for player hero pools; maintained without game API integration.';
CREATE TABLE media_assets (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    uploaded_by UUID NOT NULL REFERENCES users(id),
    object_key TEXT NOT NULL UNIQUE,
    mime_type VARCHAR(100) NOT NULL,
    byte_size BIGINT NOT NULL CHECK (byte_size > 0),
    sha256 CHAR(64),
    access_scope TEXT NOT NULL DEFAULT 'private' CHECK (access_scope IN ('private','public')),
    scan_status TEXT NOT NULL DEFAULT 'pending' CHECK (scan_status IN ('pending','clean','rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE media_assets IS '2. Object-storage metadata for avatars, posts and evidence. No binary files or expiring signed URLs in SQL.';

-- 3. SQUAD AND PLAYER PROFILES
-- Under this section: squad identity, representatives, individual players and roster history.
CREATE TABLE squads (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    public_number BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE,
    owner_user_id UUID NOT NULL REFERENCES users(id),
    name VARCHAR(100) NOT NULL CHECK (length(trim(name)) > 0),
    slug VARCHAR(120) NOT NULL UNIQUE,
    acronym VARCHAR(15),
    bio TEXT,
    region_code VARCHAR(20) NOT NULL REFERENCES regions(code),
    timezone TEXT NOT NULL DEFAULT 'Asia/Manila',
    level_code VARCHAR(30) NOT NULL REFERENCES squad_levels(code),
    avatar_asset_id UUID REFERENCES media_assets(id),
    banner_asset_id UUID REFERENCES media_assets(id),
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','suspended','archived')),
    verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0),
    CHECK (slug = lower(slug))
);
CREATE INDEX squads_owner ON squads (owner_user_id);
COMMENT ON TABLE squads IS '3. Squad profile: name, acronym, description, level, region and branding. Ownership is separate from coaching authority.';
COMMENT ON COLUMN squads.public_number IS 'Human-friendly ABYSS display ID, not the MLBB squad ID or an authorization secret.';
CREATE TABLE squad_coaches (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    squad_id UUID NOT NULL REFERENCES squads(id),
    user_id UUID NOT NULL REFERENCES users(id),
    coach_role TEXT NOT NULL DEFAULT 'head_coach' CHECK (coach_role IN ('head_coach','assistant_coach')),
    is_primary BOOLEAN NOT NULL DEFAULT false,
    can_manage_roster BOOLEAN NOT NULL DEFAULT true,
    can_manage_scrims BOOLEAN NOT NULL DEFAULT true,
    can_message_opponents BOOLEAN NOT NULL DEFAULT true,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    left_at TIMESTAMPTZ,
    CHECK (left_at IS NULL OR left_at >= joined_at),
    UNIQUE (id, user_id, squad_id),
    UNIQUE (id, squad_id)
);
CREATE UNIQUE INDEX squad_coaches_active ON squad_coaches (squad_id, user_id) WHERE left_at IS NULL;
CREATE UNIQUE INDEX squad_coaches_one_primary ON squad_coaches (squad_id) WHERE left_at IS NULL AND is_primary;
CREATE INDEX squad_coaches_user ON squad_coaches (user_id) WHERE left_at IS NULL;
COMMENT ON TABLE squad_coaches IS '3. Coaches are the authorized squad representatives. A primary coach manages the roster, matchmaking and coach-to-coach contact.';
CREATE TABLE players (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    linked_user_id UUID UNIQUE REFERENCES users(id),
    created_by UUID NOT NULL REFERENCES users(id),
    in_game_name VARCHAR(100) NOT NULL,
    real_name VARCHAR(150),
    mlbb_account_id VARCHAR(30) NOT NULL,
    mlbb_zone_id VARCHAR(30) NOT NULL,
    current_rank_id SMALLINT REFERENCES game_ranks(id),
    current_stars INTEGER CHECK (current_stars >= 0),
    highest_rank_id SMALLINT REFERENCES game_ranks(id),
    highest_stars INTEGER CHECK (highest_stars >= 0),
    preferred_role VARCHAR(30),
    avatar_asset_id UUID REFERENCES media_assets(id),
    rank_reported_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0),
    UNIQUE (mlbb_account_id, mlbb_zone_id)
);
COMMENT ON TABLE players IS '3. MLBB player profile, current/highest rank and stars. A roster player need not have an ABYSS login.';
COMMENT ON COLUMN players.real_name IS 'Private optional roster detail; exclude from public projections.';
COMMENT ON COLUMN players.mlbb_zone_id IS 'Game account and zone stored separately as text, preserving identifiers exactly.';
CREATE TABLE player_heroes (
    player_id UUID NOT NULL REFERENCES players(id),
    hero_id SMALLINT NOT NULL REFERENCES heroes(id),
    preference_order SMALLINT NOT NULL CHECK (preference_order > 0),
    PRIMARY KEY (player_id, hero_id),
    UNIQUE (player_id, preference_order)
);
COMMENT ON TABLE player_heroes IS '3. Player hero pool: one row per hero, not comma-separated values.';
CREATE TABLE squad_roster (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    squad_id UUID NOT NULL REFERENCES squads(id),
    player_id UUID NOT NULL REFERENCES players(id),
    added_by_coach_id UUID NOT NULL,
    roster_role TEXT NOT NULL CHECK (roster_role IN ('captain','starter','substitute')),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    left_at TIMESTAMPTZ,
    CHECK (left_at IS NULL OR left_at >= joined_at),
    FOREIGN KEY (added_by_coach_id, squad_id) REFERENCES squad_coaches(id, squad_id)
);
CREATE UNIQUE INDEX roster_one_active_squad ON squad_roster (player_id) WHERE left_at IS NULL;
CREATE UNIQUE INDEX roster_one_active_captain ON squad_roster (squad_id) WHERE left_at IS NULL AND roster_role = 'captain';
CREATE INDEX roster_squad ON squad_roster (squad_id, joined_at DESC);
COMMENT ON TABLE squad_roster IS '3. Membership history. A coach registers each player for their squad; no fixed player1/player2 columns.';

-- 4. MATCHMAKING, INVITATIONS AND SCHEDULES
-- Under this section: availability, challenges, accepted matches and negotiated changes.
CREATE TABLE squad_availability (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    squad_id UUID NOT NULL REFERENCES squads(id),
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (ends_at > starts_at)
);
CREATE INDEX availability_squad_time ON squad_availability (squad_id, starts_at, ends_at);
COMMENT ON TABLE squad_availability IS '4. Optional concrete availability windows. A later service can expand recurring availability.';
CREATE TABLE scrim_invites (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    sender_squad_id UUID NOT NULL REFERENCES squads(id),
    recipient_squad_id UUID NOT NULL REFERENCES squads(id),
    created_by UUID NOT NULL REFERENCES users(id),
    created_by_coach_id UUID NOT NULL,
    proposed_start TIMESTAMPTZ NOT NULL,
    proposed_end TIMESTAMPTZ NOT NULL,
    series_format TEXT NOT NULL DEFAULT 'best_of' CHECK (series_format IN ('best_of','fixed_games')),
    game_count SMALLINT NOT NULL CHECK (game_count BETWEEN 1 AND 99),
    message TEXT,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','declined','cancelled','expired')),
    expires_at TIMESTAMPTZ NOT NULL,
    responded_by UUID REFERENCES users(id),
    responded_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0),
    UNIQUE (id, sender_squad_id, recipient_squad_id),
    FOREIGN KEY (created_by_coach_id, created_by, sender_squad_id)
        REFERENCES squad_coaches(id, user_id, squad_id),
    CHECK (sender_squad_id <> recipient_squad_id),
    CHECK (proposed_end > proposed_start),
    CHECK (expires_at > created_at AND expires_at <= proposed_start),
    CHECK (series_format <> 'best_of' OR game_count % 2 = 1),
    CHECK ((status = 'pending' AND responded_at IS NULL) OR (status <> 'pending' AND responded_at IS NOT NULL))
);
CREATE INDEX invites_inbox ON scrim_invites (recipient_squad_id, status, created_at DESC, id);
CREATE INDEX invites_sent ON scrim_invites (sender_squad_id, status, created_at DESC, id);
CREATE INDEX invites_expiry ON scrim_invites (expires_at) WHERE status = 'pending';
CREATE UNIQUE INDEX invites_pending_pair_slot ON scrim_invites
    (LEAST(sender_squad_id,recipient_squad_id), GREATEST(sender_squad_id,recipient_squad_id), proposed_start)
    WHERE status = 'pending';
COMMENT ON TABLE scrim_invites IS '4. Received and sent invites query the same authoritative invitation.';
CREATE TABLE scrims (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    invite_id UUID NOT NULL UNIQUE,
    home_squad_id UUID NOT NULL REFERENCES squads(id),
    away_squad_id UUID NOT NULL REFERENCES squads(id),
    scheduled_start TIMESTAMPTZ NOT NULL,
    scheduled_end TIMESTAMPTZ NOT NULL,
    series_format TEXT NOT NULL CHECK (series_format IN ('best_of','fixed_games')),
    game_count SMALLINT NOT NULL CHECK (game_count BETWEEN 1 AND 99),
    status TEXT NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled','in_progress','awaiting_result','disputed','completed','cancelled','no_show')),
    actual_start TIMESTAMPTZ,
    actual_end TIMESTAMPTZ,
    cancellation_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0),
    FOREIGN KEY (invite_id, home_squad_id, away_squad_id)
        REFERENCES scrim_invites(id, sender_squad_id, recipient_squad_id),
    CHECK (home_squad_id <> away_squad_id),
    CHECK (scheduled_end > scheduled_start),
    CHECK (actual_end IS NULL OR (actual_start IS NOT NULL AND actual_end >= actual_start)),
    CHECK (series_format <> 'best_of' OR game_count % 2 = 1)
);
CREATE INDEX scrims_home_schedule ON scrims (home_squad_id, scheduled_start, scheduled_end);
CREATE INDEX scrims_away_schedule ON scrims (away_squad_id, scheduled_start, scheduled_end);
COMMENT ON TABLE scrims IS '4. Two squads per series. Handler copies accepted terms atomically and locks both squads to prevent overlaps.';
CREATE TABLE scrim_reschedule_requests (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    scrim_id UUID NOT NULL REFERENCES scrims(id),
    proposed_by_squad_id UUID NOT NULL REFERENCES squads(id),
    created_by UUID NOT NULL REFERENCES users(id),
    expected_scrim_version BIGINT NOT NULL CHECK (expected_scrim_version > 0),
    proposed_start TIMESTAMPTZ NOT NULL,
    proposed_end TIMESTAMPTZ NOT NULL,
    reason TEXT,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','declined','cancelled','expired')),
    expires_at TIMESTAMPTZ NOT NULL,
    decided_by UUID REFERENCES users(id),
    decided_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (proposed_end > proposed_start),
    CHECK (expires_at > created_at),
    CHECK ((status = 'pending' AND decided_at IS NULL) OR (status <> 'pending' AND decided_at IS NOT NULL))
);
CREATE UNIQUE INDEX reschedule_one_pending ON scrim_reschedule_requests (scrim_id) WHERE status = 'pending';
COMMENT ON TABLE scrim_reschedule_requests IS '4. Opposing squad accepts negotiated changes; stale proposals cannot overwrite newer schedules.';
CREATE TABLE scrim_lineups (
    scrim_id UUID NOT NULL REFERENCES scrims(id),
    squad_id UUID NOT NULL REFERENCES squads(id),
    player_id UUID NOT NULL REFERENCES players(id),
    in_game_name_snapshot VARCHAR(100) NOT NULL,
    role_snapshot VARCHAR(30),
    PRIMARY KEY (scrim_id, player_id)
);
COMMENT ON TABLE scrim_lineups IS '4. Historical lineup snapshot; roster transfers cannot rewrite past participation.';

-- 5. RESULTS, SCREENSHOT PROOF, OCR AND RATINGS
-- Under this section: submitted results and human confirmation; OCR is supporting evidence.
CREATE TABLE result_submissions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    scrim_id UUID NOT NULL REFERENCES scrims(id),
    submitted_by_squad_id UUID NOT NULL REFERENCES squads(id),
    submitted_by UUID NOT NULL REFERENCES users(id),
    home_wins SMALLINT NOT NULL CHECK (home_wins >= 0),
    away_wins SMALLINT NOT NULL CHECK (away_wins >= 0),
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','confirmed','disputed','rejected','superseded')),
    reviewed_by UUID REFERENCES users(id),
    reviewed_at TIMESTAMPTZ,
    review_note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (scrim_id, id)
);
CREATE INDEX results_scrim_time ON result_submissions (scrim_id, created_at DESC);
CREATE UNIQUE INDEX result_one_pending_per_squad ON result_submissions (scrim_id, submitted_by_squad_id) WHERE status = 'pending';
COMMENT ON TABLE result_submissions IS '5. Preserve submitted claims; corrections are new rows. Only approved claims become canonical results.';
CREATE TABLE result_evidence (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    submission_id UUID NOT NULL REFERENCES result_submissions(id),
    asset_id UUID NOT NULL REFERENCES media_assets(id),
    game_number SMALLINT CHECK (game_number > 0),
    ocr_status TEXT NOT NULL DEFAULT 'pending' CHECK (ocr_status IN ('pending','processing','succeeded','failed','not_requested')),
    ocr_extracted JSONB,
    ocr_confidence NUMERIC(5,4) CHECK (ocr_confidence BETWEEN 0 AND 1),
    ocr_model_version TEXT,
    processed_at TIMESTAMPTZ,
    UNIQUE (submission_id, asset_id)
);
COMMENT ON TABLE result_evidence IS '5. Screenshot proof and optional OCR output for moderator logs. OCR success does not establish result validity.';
CREATE TABLE scrim_results (
    scrim_id UUID PRIMARY KEY REFERENCES scrims(id),
    accepted_submission_id UUID NOT NULL UNIQUE,
    home_wins SMALLINT NOT NULL CHECK (home_wins >= 0),
    away_wins SMALLINT NOT NULL CHECK (away_wins >= 0),
    outcome TEXT NOT NULL CHECK (outcome IN ('home_win','away_win','draw','void')),
    finalized_by UUID NOT NULL REFERENCES users(id),
    finalized_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0),
    FOREIGN KEY (scrim_id, accepted_submission_id) REFERENCES result_submissions(scrim_id, id),
    CHECK ((outcome = 'home_win' AND home_wins > away_wins)
        OR (outcome = 'away_win' AND away_wins > home_wins)
        OR (outcome = 'draw' AND home_wins = away_wins) OR outcome = 'void')
);
COMMENT ON TABLE scrim_results IS '5. One canonical series result. FinalizeResult validates accepted claim, scores and series rules.';
CREATE TABLE rating_seasons (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(80) NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    algorithm_version VARCHAR(40) NOT NULL,
    rules JSONB NOT NULL DEFAULT '{}'::jsonb,
    CHECK (ends_at > starts_at)
);
COMMENT ON TABLE rating_seasons IS '5. ABYSS rating periods and versioned rules, independent of official MLBB ranks/seasons.';
CREATE TABLE squad_ratings (
    season_id UUID NOT NULL REFERENCES rating_seasons(id),
    squad_id UUID NOT NULL REFERENCES squads(id),
    rating NUMERIC(12,4) NOT NULL,
    rated_series INTEGER NOT NULL DEFAULT 0 CHECK (rated_series >= 0),
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (season_id, squad_id)
);
COMMENT ON TABLE squad_ratings IS '5. Authoritative platform rating for matchmaking, not a client-editable profile field.';
CREATE TABLE rating_changes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    season_id UUID NOT NULL REFERENCES rating_seasons(id),
    squad_id UUID NOT NULL REFERENCES squads(id),
    scrim_id UUID NOT NULL REFERENCES scrims(id),
    result_version BIGINT NOT NULL CHECK (result_version > 0),
    rating_before NUMERIC(12,4) NOT NULL,
    rating_after NUMERIC(12,4) NOT NULL,
    algorithm_version VARCHAR(40) NOT NULL,
    reason TEXT NOT NULL CHECK (reason IN ('result','correction')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (season_id, squad_id, scrim_id, result_version)
);
COMMENT ON TABLE rating_changes IS '5. Auditable, deduplicated rating effects; corrections require a defined adjustment/recalculation policy.';

-- 6. SOCIAL FEED AND SQUAD MESSAGING
-- Under this section: profile posts, attachments, squad conversations and per-user read state.
CREATE TABLE squad_posts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    squad_id UUID NOT NULL REFERENCES squads(id),
    author_user_id UUID NOT NULL REFERENCES users(id),
    body TEXT NOT NULL DEFAULT '',
    label VARCHAR(80),
    visibility TEXT NOT NULL DEFAULT 'public' CHECK (visibility IN ('public','squad')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0)
);
CREATE INDEX posts_squad_feed ON squad_posts (squad_id, created_at DESC, id) WHERE deleted_at IS NULL;
COMMENT ON TABLE squad_posts IS '6. Home/profile feed posts with optional label and public or squad-only visibility.';
CREATE TABLE post_assets (
    post_id UUID NOT NULL REFERENCES squad_posts(id),
    asset_id UUID NOT NULL REFERENCES media_assets(id),
    sort_order SMALLINT NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    PRIMARY KEY (post_id, asset_id),
    UNIQUE (post_id, sort_order)
);
COMMENT ON TABLE post_assets IS '6. Ordered post attachments; handler requires text or at least one attachment.';
CREATE TABLE conversations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    first_squad_id UUID NOT NULL REFERENCES squads(id),
    second_squad_id UUID NOT NULL REFERENCES squads(id),
    next_sequence BIGINT NOT NULL DEFAULT 1 CHECK (next_sequence > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (first_squad_id < second_squad_id),
    UNIQUE (first_squad_id, second_squad_id)
);
COMMENT ON TABLE conversations IS '6. One direct conversation per unordered squad pair; UUID ordering canonicalizes the pair.';
CREATE TABLE messages (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    conversation_id UUID NOT NULL REFERENCES conversations(id),
    sequence BIGINT NOT NULL CHECK (sequence > 0),
    sender_user_id UUID NOT NULL REFERENCES users(id),
    sender_squad_id UUID NOT NULL REFERENCES squads(id),
    sender_coach_id UUID NOT NULL,
    body TEXT NOT NULL CHECK (length(trim(body)) BETWEEN 1 AND 10000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    UNIQUE (conversation_id, sequence),
    FOREIGN KEY (sender_coach_id, sender_user_id, sender_squad_id)
        REFERENCES squad_coaches(id, user_id, squad_id)
);
COMMENT ON TABLE messages IS '6. Coach-to-coach messages. The composite foreign key proves that the sender is a coach of the sending squad.';
CREATE TABLE conversation_reads (
    conversation_id UUID NOT NULL REFERENCES conversations(id),
    user_id UUID NOT NULL REFERENCES users(id),
    last_read_sequence BIGINT NOT NULL DEFAULT 0 CHECK (last_read_sequence >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (conversation_id, user_id)
);
COMMENT ON TABLE conversation_reads IS '6. Individual read cursor for each authorized representative; advance monotonically.';

-- 7. NOTIFICATIONS
-- Under this section: durable notification intent and per-user read state.
CREATE TABLE notifications (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    recipient_user_id UUID NOT NULL REFERENCES users(id),
    recipient_squad_id UUID REFERENCES squads(id),
    source_event_id UUID NOT NULL,
    kind VARCHAR(80) NOT NULL,
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    read_at TIMESTAMPTZ,
    UNIQUE (recipient_user_id, source_event_id, kind)
);
CREATE INDEX notifications_unread ON notifications (recipient_user_id, created_at DESC, id) WHERE read_at IS NULL;
COMMENT ON TABLE notifications IS '7. Durable notification/read state; source-event ID deduplicates retries without FK to the prunable outbox.';

-- 8. FEEDBACK, REPORTS, VERIFICATION AND MODERATION
-- Under this section: manual review, evidence, reasons and accountable decisions.
CREATE TABLE feedback (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    submitted_by UUID NOT NULL REFERENCES users(id),
    squad_id UUID REFERENCES squads(id),
    scrim_id UUID REFERENCES scrims(id),
    category VARCHAR(80) NOT NULL,
    body TEXT NOT NULL CHECK (length(trim(body)) > 0),
    status TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new','reviewing','resolved','closed')),
    assigned_to UUID REFERENCES users(id),
    response TEXT,
    resolved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0)
);
CREATE INDEX feedback_queue ON feedback (status, created_at, id);
COMMENT ON TABLE feedback IS '8. Platform feedback and optional scrim feedback; not an automatic disciplinary report.';
CREATE TABLE reports (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    reporter_user_id UUID NOT NULL REFERENCES users(id),
    reporter_squad_id UUID NOT NULL REFERENCES squads(id),
    reported_squad_id UUID NOT NULL REFERENCES squads(id),
    scrim_id UUID REFERENCES scrims(id),
    category VARCHAR(80) NOT NULL,
    description TEXT NOT NULL CHECK (length(trim(description)) > 0),
    status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','investigating','resolved','dismissed')),
    assigned_to UUID REFERENCES users(id),
    resolved_by UUID REFERENCES users(id),
    resolution TEXT,
    resolved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0),
