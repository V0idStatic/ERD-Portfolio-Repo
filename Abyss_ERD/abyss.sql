CREATE OR REPLACE VIEW vw_squad_profile AS
SELECT
    s.id AS squad_id,
    s.public_number AS squad_number,
    s.name AS squad_name,
    s.slug AS squad_slug,
    s.acronym AS squad_acronym,
    s.bio AS squad_bio,
    s.status AS squad_status,
    s.verified_at IS NOT NULL AS is_verified,
    r.name AS region_name,
    r.code AS region_code,
    s.timezone,
    sl.name AS squad_level,
    owner.username AS owner_username,
    owner.display_name AS owner_display_name,
    coaching.primary_coach_name,
    COALESCE(coaching.coaches, '[]'::jsonb) AS coaches,
    avatar.object_key AS avatar_key,
    banner.object_key AS banner_key,
    COALESCE(roster.player_count, 0) AS player_count,
    COALESCE(roster.players, '[]'::jsonb) AS players,
    s.created_at,
    s.updated_at
FROM squads s
JOIN regions r ON r.code = s.region_code
JOIN squad_levels sl ON sl.code = s.level_code
JOIN users owner ON owner.id = s.owner_user_id
LEFT JOIN media_assets avatar ON avatar.id = s.avatar_asset_id
LEFT JOIN media_assets banner ON banner.id = s.banner_asset_id
LEFT JOIN LATERAL (
    SELECT
        max(COALESCE(u.display_name, u.username)) FILTER (WHERE c.is_primary) AS primary_coach_name,
        jsonb_agg(
            jsonb_build_object(
                'coachName', COALESCE(u.display_name, u.username),
                'coachRole', c.coach_role,
                'isPrimary', c.is_primary,
                'managesRoster', c.can_manage_roster,
                'managesScrims', c.can_manage_scrims
            ) ORDER BY c.is_primary DESC, c.coach_role, COALESCE(u.display_name, u.username)
        ) AS coaches
    FROM squad_coaches c
    JOIN users u ON u.id = c.user_id
    WHERE c.squad_id = s.id AND c.left_at IS NULL
) coaching ON true
LEFT JOIN LATERAL (
    SELECT
        count(*)::integer AS player_count,
        jsonb_agg(
            jsonb_build_object(
                'playerName', p.in_game_name,
                'rosterRole', sr.roster_role,
                'preferredRole', p.preferred_role,
                'currentRank', current_rank.name,
                'currentStars', p.current_stars,
                'highestRank', highest_rank.name,
                'highestStars', p.highest_stars,
                'avatarKey', player_avatar.object_key,
                'heroPool', COALESCE(hero_pool.heroes, '[]'::jsonb)
            ) ORDER BY CASE sr.roster_role WHEN 'captain' THEN 0 WHEN 'starter' THEN 1 ELSE 2 END,
                       p.in_game_name
        ) AS players
    FROM squad_roster sr
    JOIN players p ON p.id = sr.player_id
    LEFT JOIN game_ranks current_rank ON current_rank.id = p.current_rank_id
    LEFT JOIN game_ranks highest_rank ON highest_rank.id = p.highest_rank_id
    LEFT JOIN media_assets player_avatar ON player_avatar.id = p.avatar_asset_id
    LEFT JOIN LATERAL (
        SELECT jsonb_agg(h.name ORDER BY ph.preference_order) AS heroes
        FROM player_heroes ph
        JOIN heroes h ON h.id = ph.hero_id
        WHERE ph.player_id = p.id
    ) hero_pool ON true
    WHERE sr.squad_id = s.id AND sr.left_at IS NULL
) roster ON true;
COMMENT ON VIEW vw_squad_profile IS '11A. Display-ready squad profile. Foreign keys are resolved to names, asset keys and a public player roster.';

CREATE OR REPLACE VIEW vw_squad_schedule AS
SELECT
    s.id AS squad_id,
    s.public_number AS squad_number,
    s.name AS squad_name,
    opponent.id AS opponent_id,
    opponent.public_number AS opponent_number,
    opponent.name AS opponent_name,
    opponent.acronym AS opponent_acronym,
    opponent_avatar.object_key AS opponent_avatar_key,
    sc.id AS scrim_id,
    sc.scheduled_start,
    sc.scheduled_end,
    sc.series_format,
    sc.game_count,
    sc.status AS scrim_status,
    CASE WHEN sc.home_squad_id = s.id THEN result.home_wins ELSE result.away_wins END AS own_wins,
    CASE WHEN sc.home_squad_id = s.id THEN result.away_wins ELSE result.home_wins END AS opponent_wins,
    CASE
        WHEN result.outcome IS NULL THEN NULL
        WHEN result.outcome = 'void' THEN 'Void'
        WHEN result.outcome = 'draw' THEN 'Draw'
        WHEN (result.outcome = 'home_win' AND sc.home_squad_id = s.id)
          OR (result.outcome = 'away_win' AND sc.away_squad_id = s.id) THEN 'Win'
        ELSE 'Loss'
    END AS result_label,
    CASE
        WHEN result.home_wins IS NULL THEN NULL
        WHEN sc.home_squad_id = s.id THEN result.home_wins::text || '-' || result.away_wins::text
        ELSE result.away_wins::text || '-' || result.home_wins::text
    END AS score_display
FROM scrims sc
JOIN squads s ON s.id IN (sc.home_squad_id, sc.away_squad_id)
JOIN squads opponent ON opponent.id = CASE WHEN s.id = sc.home_squad_id THEN sc.away_squad_id ELSE sc.home_squad_id END
LEFT JOIN media_assets opponent_avatar ON opponent_avatar.id = opponent.avatar_asset_id
LEFT JOIN scrim_results result ON result.scrim_id = sc.id;
